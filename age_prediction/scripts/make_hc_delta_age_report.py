#!/usr/bin/env python3
"""Summarize HC delta_age (= pred_age - true_age) from the age-prediction CV outputs.

Reads the per-fold test-prediction CSVs written by
  run_age_acceleration_cv.py        (leave-studies-out, files: *_genus_range_1_80.csv)
  run_age_predict_random_split.py   (random split,        files: *_random_range_1_80.csv)
keeps only HC test samples, and builds one xlsx report with
  site summary, fold summary, per-sample detail and a readme sheet.
Does not touch any existing result file.

Env used previously: /home/xuhuan/miniconda3/envs/R4/bin/python
"""
import argparse
import glob
import os
import re

import pandas as pd

META_PATH = "/home/xuhuan/global_oral/data/metadata-and-biom-v2-qc/metadata_oral_qc_dedup.tsv"

RESULT_ROOT = "/home/xuhuan/global_oral/age_prediction/result"
LOS_DIR = os.path.join(RESULT_ROOT, "leave_studies_out_rf")
RAND_DIR = os.path.join(RESULT_ROOT, "random_split_rf")
OUT_PATH = os.path.join(RESULT_ROOT, "figures", "hc_delta_age_site_summary.xlsx")

FNAME_RE = re.compile(r"age_predict_test_(\d+)_(.+?)_(genus|random)_range_1_80\.csv")


def q25(x):
    return x.quantile(0.25)


def q75(x):
    return x.quantile(0.75)


def fold_summaries(x):
    hc_fold = x[x["status_cleaned"] == "HC"]
    g = hc_fold.groupby(["site", "fold"])["delta_age"]
    return g.agg(n="size", mean="mean", median="median", q1=q25, q3=q75,
                 min="min", max="max").reset_index()


def site_summary(x):
    g = x.groupby("site")["delta_age"]
    out = g.agg(n="size", mean="mean", median="median", q1=q25, q3=q75,
                min="min", max="max").reset_index()
    # median_delta is exactly the figure's zero anchor (hc_med) per site
    return out.rename(columns={"median": "median_delta (= figure hc_med anchor)"})


def collect(dir_path, token, scheme, meta):
    files = sorted(glob.glob(os.path.join(dir_path, f"*_{token}_range_1_80.csv")))
    if not files:
        return pd.DataFrame()
    frames = []
    for f in files:
        m = FNAME_RE.match(os.path.basename(f))
        fold, site = int(m.group(1)), m.group(2)
        df = pd.read_csv(f)
        df.insert(1, "site", site)
        df.insert(2, "fold", fold)
        frames.append(df)
    all_df = pd.concat(frames, ignore_index=True)
    all_df["delta_age"] = all_df["pred_age"] - all_df["true_age"]
    all_df["scheme"] = scheme
    all_df = all_df.merge(meta[["sample_id", "bioproject_id", "status_cleaned"]],
                          on="sample_id", how="left")
    cols = ["sample_id", "bioproject_id", "site", "fold", "scheme",
            "true_age", "pred_age", "delta_age", "status_cleaned"]
    return all_df[cols]


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--out", default=OUT_PATH)
    args = ap.parse_args()

    meta = pd.read_csv(META_PATH, sep="\t", low_memory=False)

    loso = collect(LOS_DIR, "genus", "leave-studies-out", meta)
    rand = collect(RAND_DIR, "random", "random-split", meta)

    site_s = site_summary(loso[loso["status_cleaned"] == "HC"])
    site_s_rand = site_summary(rand[rand["status_cleaned"] == "HC"])
    fold_s = fold_summaries(loso)
    samples = pd.concat([loso, rand], ignore_index=True)

    # consistency check: pooled HC median must equal the figure's hc_med anchor
    # (in the figure stats csv the HC values live in the hc_med/hc_n columns of
    # the disease rows, one anchor per site)
    stats_csv = os.path.join(RESULT_ROOT, "figures",
                             "age_disease_microbiome_age_acceleration_1row_stats.csv")
    try:
        stats = pd.read_csv(stats_csv).drop_duplicates("site")
        site_s = site_s.sort_values("site").reset_index(drop=True)
        stats = stats.sort_values("site").reset_index(drop=True)
        chk = pd.DataFrame({
            "site": site_s["site"],
            "report_hc_n": site_s["n"].astype(int),
            "figure_hc_n": stats["hc_n"].astype(int),
            "report_hc_med": site_s["median_delta (= figure hc_med anchor)"].round(2),
            "figure_hc_med": stats["hc_med"].round(2),
            "match": (site_s["n"].astype(int).values == stats["hc_n"].astype(int).values)
                     & (site_s["median_delta (= figure hc_med anchor)"].round(2).values
                        == stats["hc_med"].round(2).values),
        })
        print("per-site check vs figure stats csv (pooled HC anchor):")
        print(chk.to_string(index=False))
    except FileNotFoundError:
        print(f"[warn] stats csv not found: {stats_csv}")

    readme = pd.DataFrame({"item": [
        "source (leave-studies-out)", "source (random split)",
        "delta_age definition", "HC filter", "site_summary_sheets",
        "fold_summary_lso", "hc_delta_samples", "generated by"],
        "value": [
            os.path.relpath(LOS_DIR, os.path.dirname(RESULT_ROOT)),
            os.path.relpath(RAND_DIR, os.path.dirname(RESULT_ROOT)),
            "pred_age - true_age (out-of-fold test prediction)",
            "status_cleaned == 'HC' (from metadata_oral_qc_dedup.tsv)",
            "_lso = leave-studies-out (figure 2col source); _random = random-split counterpart",
            "HC delta_age per site x fold (single-fold values fluctuate; figure anchors use pooled sites)",
            "one row per HC test sample, both CV schemes",
            "scripts/make_hc_delta_age_report.py"]})

    os.makedirs(os.path.dirname(args.out), exist_ok=True)
    with pd.ExcelWriter(args.out, engine="openpyxl") as xw:
        readme.to_excel(xw, sheet_name="readme", index=False)
        site_s.to_excel(xw, sheet_name="hc_site_summary_lso", index=False)
        site_s_rand.to_excel(xw, sheet_name="hc_site_summary_random", index=False)
        fold_s.to_excel(xw, sheet_name="hc_fold_summary_lso", index=False)
        samples.to_excel(xw, sheet_name="hc_delta_samples", index=False)
    print(f"[done] wrote {args.out}: "
          f"lso HC n={len(site_s.n)} sites, sample rows={len(samples)}")

    print("\nHC delta_age site summary (leave-studies-out, figure source):")
    print(site_s.to_string(index=False))


if __name__ == "__main__":
    main()