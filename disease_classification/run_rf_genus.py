"""
Random Forest on genus-level splits generated by disease_predict.ipynb (genus version).

Adapted from the OTU-era run_rf.py; file names updated to the genus naming scheme:
    part 1: data/lso_genus_{train,test}_{site}_{disease}_{study}.biom
    part 2: data/five_fold_genus_{train,test}_{site}_{study}_{fold}.biom
    part 3: data/genus_{train,test}_{wc|loco}_{site}_{disease}_{continent}[_{study}].biom
    part 4: data/{train,test}_cd_{site}_train_{A}_test_{B}.biom
    part 5: data/genus_{train,test}_lc_{site}_{disease}_k{k}_r{rep}_test_{study}.biom

Outputs (one csv per part, per-sample predicted probabilities):
    result/RF_results_lso.csv
    result/RF_results_five_fold.csv
    result/RF_results_continent.csv
    result/RF_results_cross_disease.csv
    result/RF_results_lc.csv

Each part can be toggled with the PARTS list below.
"""
import biom
import pandas as pd
import numpy as np
from sklearn.ensemble import RandomForestClassifier
from sklearn.metrics import roc_auc_score

N_JOBS = 16
PARTS = ["continent", "cross_disease", "lc"]


def make_rf():
    # fresh model per split so nothing leaks between folds
    return RandomForestClassifier(
        n_estimators=500, max_depth=5, max_features="log2",
        random_state=42, n_jobs=N_JOBS)


def run_split(run_info, meta_path, name_fn, out_csv):
    """
    name_fn(row) -> (train_biom_path, test_biom_path, fold_name)
    Trains one RF per row, collects per-sample predicted probabilities,
    prints per-fold AUC, writes out_csv.
    """
    metadata = pd.read_csv(meta_path, sep="\t", index_col=0)
    fold, pred_prob, sample_id = [], [], []
    for i in run_info.index.values:
        row = run_info.loc[i]
        train_table, test_table, fold_name = name_fn(row)

        X_train = biom.load_table(train_table).norm(axis='sample', inplace=False).to_dataframe().T
        X_test  = biom.load_table(test_table).norm(axis='sample', inplace=False).to_dataframe().T
        test_sid = X_test.index.values

        y_train = metadata.loc[X_train.index.values, "group"]
        y_test  = metadata.loc[X_test.index.values,  "group"]

        # align test features to train features (biom filter already does this,
        # but guard against any column mismatch after norm/to_dataframe)
        X_test = X_test.reindex(columns=X_train.columns, fill_value=0)

        rf = make_rf()
        rf.fit(X_train.values, y_train)
        y_prob = rf.predict_proba(X_test.values)[:, 1]

        pred_prob += list(y_prob)
        sample_id += list(test_sid)
        fold      += [fold_name] * len(y_prob)

        # AUC only defined if test has both classes
        if len(np.unique(y_test)) == 2:
            print(f"{fold_name}\tAUC={roc_auc_score(y_test, y_prob):.4f}", flush=True)
        else:
            print(f"{fold_name}\tAUC=NA (single-class test set)", flush=True)

    pd.DataFrame({"sampel_id": sample_id, "group": fold, "pred_prob": pred_prob}) \
        .to_csv(out_csv, index=False)
    print(f"  -> wrote {out_csv}\n", flush=True)


# =========================================================================
# part 1: leave-one-study-out
# =========================================================================
if "lso" in PARTS:
    def name_lso(r):
        s, d, st = r['site'], r['disease'], r['study']
        return (f"data/lso_genus_train_{s}_{d}_{st}.biom",
                f"data/lso_genus_test_{s}_{d}_{st}.biom",
                f"{s}_{d}_{st}")

    print("### part 1: leave-one-study-out", flush=True)
    run_split(pd.read_csv("run_info_genus.csv"), "meta_genus.tsv",
              name_lso, "result/RF_results_lso.csv")


# =========================================================================
# part 2: five-fold (oral/gut paired)
# csv columns: site,fold,study  ;  filename order is _{site}_{study}_{fold}
# =========================================================================
if "five_fold" in PARTS:
    def name_5fold(r):
        s, f, st = r['site'], r['fold'], r['study']
        return (f"data/five_fold_genus_train_{s}_{st}_{f}.biom",
                f"data/five_fold_genus_test_{s}_{st}_{f}.biom",
                f"{s}_{st}_{f}")

    print("### part 2: five-fold oral/gut", flush=True)
    run_split(pd.read_csv("run_info_oral_gut_genus.csv"), "meta_oral_gut_genus.tsv",
              name_5fold, "result/RF_results_five_fold.csv")


# =========================================================================
# part 3: continent (within_continent + leave_one_continent_out)
# csv columns: site,disease,continent,test_study,split_type
# within-continent files carry the continent + test_study; LOCO files carry
# only the continent (held-out continent).
# =========================================================================
if "continent" in PARTS:
    def name_continent(r):
        s, d = r['site'], r['disease']
        st_type = str(r['split_type'])
        cont, test_study = r['continent'], r['test_study']

        if st_type in ("wc", "within_continent"):
            base = f"wc_{s}_{d}_{cont}_{test_study}"
        else:  # leave_one_continent_out / loco
            # genus version: loco folds test one study at a time, so the file
            # name also carries the test_study (same scheme as wc)
            base = f"loco_{s}_{d}_{cont}_{test_study}"
        return (f"data/genus_train_{base}.biom",
                f"data/genus_test_{base}.biom",
                base)

    print("### part 3: within-continent + leave-one-continent-out", flush=True)
    run_split(pd.read_csv("run_info_continent_genus.csv", dtype={"test_study": str}),
              "meta_genus.tsv",
              name_continent, "result/RF_results_continent.csv")


# =========================================================================
# part 4: cross-disease (train on A, test on B)
# csv columns: site,train_disease,test_disease,n_train,n_test,n_train_case,n_test_case,split_type
# =========================================================================
if "cross_disease" in PARTS:
    def name_cross_disease(r):
        s, a, b = r['site'], r['train_disease'], r['test_disease']
        base = f"cd_{s}_train_{a}_test_{b}"
        return (f"data/train_{base}.biom",
                f"data/test_{base}.biom",
                base)

    print("### part 4: cross-disease", flush=True)
    run_split(pd.read_csv("run_info_cross_disease_genus.csv"), "meta_genus.tsv",
              name_cross_disease, "result/RF_results_cross_disease.csv")


# =========================================================================
# part 5: learning curve
# csv columns: site,disease,n_studies,repeat,subset,test_study,split_type
# =========================================================================
if "lc" in PARTS:
    def name_lc(r):
        s, d = r['site'], r['disease']
        k, rep, test_study = r['n_studies'], r['repeat'], r['test_study']
        base = f"lc_{s}_{d}_k{k}_r{rep}_test_{test_study}"
        return (f"data/genus_train_{base}.biom",
                f"data/genus_test_{base}.biom",
                base)

    print("### part 5: learning curve", flush=True)
    run_split(pd.read_csv("run_info_lc_genus.csv", dtype={"test_study": str}),
              "meta_genus.tsv",
              name_lc, "result/RF_results_lc.csv")