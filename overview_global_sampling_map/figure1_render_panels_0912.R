# Panel A : pipeline diagram (externally-authored draw.io SVG)
# ============================================================================
render_panel_A_funnel <- function(out_dir) {
  # Panel a is the externally-authored draw.io pipeline diagram. The shipped
  # companion PNG (rasterized from the SVG in a browser) is the source of
  # truth; the SVG is only rasterized (rsvg > magick) when the PNG is missing.
  src_svg <- file.path(script_dir, "results", "global-oral-fig1a-260912.drawio.svg")
  src_png <- file.path(script_dir, "results", "global-oral-fig1a-260912.drawio.png")
  dst     <- file.path(out_dir, panel_png["A"])
  dir.create(out_dir, recursive = TRUE, showWarnings = FALSE)

  # Destination already is the drawio PNG -> nothing to do (keeps the exact
  # raster the author reviewed, avoids re-rasterizing the foreignObject SVG).

  ok <- file.exists(dst) &&
    normalizePath(dst, mustWork = FALSE) == normalizePath(src_png, mustWork = FALSE)
  if (!ok && file.exists(src_png))
    ok <- tryCatch({ file.copy(src_png, dst, overwrite = TRUE); TRUE },
                   error = function(e) FALSE)
  if (!ok && file.exists(src_svg)) {
    if (requireNamespace("rsvg", quietly = TRUE))
      ok <- !inherits(tryCatch({ rsvg::rsvg_png(src_svg, dst, width = 6420); NULL },
                                error = function(e) e), "error")
    if (!ok && requireNamespace("magick", quietly = TRUE))
      ok <- !inherits(tryCatch({
        img <- magick::image_read_svg(src_svg, width = 6420)
        magick::image_write(img, path = dst, format = "png"); NULL
      }, error = function(e) e), "error")
  }
  if (!ok || !file.exists(dst))
    return(sprintf("cannot produce panel a: need %s or %s", src_png, src_svg))
  invisible(NULL)
}

