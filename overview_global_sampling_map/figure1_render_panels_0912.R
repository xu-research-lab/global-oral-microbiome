                 quiet = TRUE),
    DEPTH = list(fn = render_panel_depth,               name = "sequencing-depth histogram"),
    COHORT = list(fn = render_panel_cohort,             name = "cohort composition"),
    DISEASE = list(fn = render_panel_disease,           name = "top-20 disease status"),
    PLACEHOLDER = list(fn = render_panel_placeholder,   name = "reserved subplot placeholder"),
    PREV  = list(fn = render_panel_prevalence,          name = "core-taxa prevalence"),
    DENS  = list(fn = render_panel_density,             name = "top-5 phylum density"),
    SHAN  = list(fn = render_panel_shannon,             name = "alpha diversity (Shannon)"),
    CONT  = list(fn = render_panel_D_phylum_continent,  name = "phylum x continent stacked (supp)"),
    AGE   = list(fn = render_panel_E_phylum_age,        name = "phylum x age stacked (supp)")
  )
  for (k in names(jobs)) {
    j <- jobs[[k]]
    cat("== rendering panel", k, "-", j$name, "... ")
    # quiet suppresses the harmless sf "planar"/countrycode/geom_point
    # warnings of the map panel (errors still surface via tryCatch).
    run <- function() {
      if (isTRUE(j$quiet)) suppressMessages(suppressWarnings(j$fn(PANEL_DIR)))
      else j$fn(PANEL_DIR)
    }
    ans <- tryCatch(run(), error = function(e) paste("error:", conditionMessage(e)))
    cat(if (is.null(ans)) "OK\n" else paste("SKIPPED:", ans, "\n", sep = " "))
  }
  invisible(NULL)
}

# ============================================================================
# Composite assembly (grid-row layout, driven by COMPOSITE_ROWS)
# ============================================================================
# `png_map` is keyed by panel_png keys; `rows` is a list of named vectors
# mapping the composite letter (e.g. "A") to a panel_png key. Each row is
# scaled so the panels fill the full output width with equal heights; the
# figure height follows from the panels' aspect ratios.
combine_panels <- function(out_dir, png_map, rows, out_base, out_width, out_dpi,
                           mg = 0.12, gap = 0.06, gap_v = 0.05, row_gap = 0.04,
                           tag_inset = c(x = 0.11, y = 0.13), tag_size = 24) {
  # rows: list of ROWS; each row = list of COLUMNS; each column = a NAMED char
  # vector letter -> panel_png key (panels inside one column are stacked).
  letrs <- unlist(lapply(rows, function(row) unlist(lapply(row, names),
                                                    use.names = FALSE)),
                  use.names = FALSE)
  keys  <- unname(unlist(lapply(rows, function(row) unlist(row))))
  if (length(letrs) != length(keys) || any(!nzchar(letrs)))
    stop("combine_panels: every column element must be a NAMED panel key")

  paths <- file.path(out_dir, png_map[keys])
  names(paths) <- letrs
  missing <- paths[!file.exists(paths)]
  if (length(missing) > 0) {
    warning("Cannot build composite, missing panel file(s): ",
            paste(sprintf("%s (%s)", names(missing), basename(missing)),
                  collapse = ", "))
    return(invisible(FALSE))
  }

  imgs <- lapply(paths, png::readPNG)
  asp  <- vapply(imgs, function(im) ncol(im) / nrow(im), numeric(1))
  names(asp) <- letrs

  usable_w <- out_width - 2 * mg
  # For each row the columns must share one height H. Column j contains n_panels
  # stacked panels, each of height = col_width / aspect, so the column height is
  #   col_width_j * inv_asp_j + gap_v * (n_panels_j - 1) = H
  # where inv_asp_j = sum(1/aspect) over the column's panels.
  # Filling the usable width with the column widths gives H.
  row_h <- vapply(rows, function(row) {
    ncols   <- length(row)
    inv_asp <- vapply(row, function(col) sum(1 / asp[names(col)]), numeric(1))
    npan    <- vapply(row, length, integer(1))
    numer <- (usable_w - gap * (ncols - 1)) + gap_v * sum((npan - 1) / inv_asp)
    numer / sum(1 / inv_asp)
  }, numeric(1))
  if (!all(is.finite(row_h)) || any(row_h <= 0))
    stop("combine_panels: row heights are not finite - aspect ratios NA?")

  Htot <- mg + sum(row_h) + row_gap * (length(rows) - 1)

  # Panel rectangles in inches, origin at the bottom-left of the canvas.
  pos  <- list()
  ytop <- Htot - mg
  for (i in seq_along(rows)) {
    row  <- rows[[i]]
    H    <- row_h[i]
    inv_asp <- vapply(row, function(col) sum(1 / asp[names(col)]), numeric(1))
    npan    <- vapply(row, length, integer(1))
    col_w <- (H - gap_v * (npan - 1)) / inv_asp
    x <- mg
    for (ci in seq_along(row)) {
      col  <- row[[ci]]
      wcol <- col_w[ci]
      yc   <- ytop - H                        # bottom of this column
      for (nm in names(col)) {                # stack panels bottom-up
        h <- wcol / asp[[nm]]
        pos[[nm]] <- c(x0 = x, x1 = x + wcol, y0 = yc, y1 = yc + h)
        yc <- yc + h + gap_v
      }
      x <- x + wcol + gap
    }
    ytop <- ytop - H - row_gap
  }

  rect_ok <- function(pr) {
    !is.null(pr) && length(pr) >= 4 &&
      all(c("x0", "x1", "y0", "y1") %in% names(pr)) &&
      all(is.finite(pr[c("x0", "x1", "y0", "y1")])) &&
      pr[["x1"]] > pr[["x0"]] && pr[["y1"]] > pr[["y0"]]
  }

  draw_figure <- function() {
    grid::grid.newpage()
    for (p in letrs) {
      pr <- pos[[p]]
      if (!rect_ok(pr)) {
        warning("combine_panels: skipping letter '", p, "' (invalid rect)")
        next
      }
      grid::pushViewport(grid::viewport(
        x = grid::unit((pr[["x0"]] + pr[["x1"]]) / 2, "in"),
        y = grid::unit((pr[["y0"]] + pr[["y1"]]) / 2, "in"),
        width  = grid::unit(pr[["x1"]] - pr[["x0"]], "in"),
        height = grid::unit(pr[["y1"]] - pr[["y0"]], "in"),
        just = "center"))
      grid::grid.raster(imgs[[p]], interpolate = TRUE)
      grid::popViewport()
      # Lowercase panel letter embedded at the panel's top-left corner with a
      # thin white halo so it stays legible over any panel content.
      tx <- pr[["x0"]] + tag_inset["x"]
      ty <- pr[["y1"]] - tag_inset["y"]
      halo <- grid::gpar(fontface = "bold", fontsize = tag_size, col = "white")
      for (dx in c(-0.018, 0, 0.018))
        for (dy in c(-0.018, 0, 0.018))
          if (dx != 0 || dy != 0)
            grid::grid.text(p, x = grid::unit(tx + dx, "in"),
                            y = grid::unit(ty + dy, "in"),
                            just = c("left", "top"), gp = halo)
      grid::grid.text(p,
                      x = grid::unit(tx, "in"),
                      y = grid::unit(ty, "in"),
                      just = c("left", "top"),
                      gp = grid::gpar(fontface = "bold", fontsize = tag_size,
                                      col = "black"))
    }
  }

  out_png <- file.path(out_dir, paste0(out_base, ".png"))
  grDevices::png(out_png, width = out_width, height = Htot, units = "in",
                 res = out_dpi, bg = "white")
  draw_figure()
  grDevices::dev.off()

  message("Saved: ", out_png)
  invisible(TRUE)
}

