# ============================================================================
# Panel f : top-15 disease statuses (horizontal stacked bars)
#   Reads top20_diseases.tsv (status, n, hc_same_study, category) written by
#   figure1_prepare_inputs_0912.py and draws a horizontal stacked bar chart
#   of the top-15 disease statuses (the aggregate "Other" status excluded),
#   ordered by decreasing total sample count (disease + same-BioProject
#   healthy controls), without sample counts printed on the bars. The count in
#   each y-axis label is the TOTAL: disease samples + matching healthy
#   controls (n + hc_same_study).
# ============================================================================
render_panel_disease <- function(out_dir) {
  if (!is.null(err <- load_libs(c("tidyverse"), AUTO_INSTALL))) return(err)
  base_sz <- as.numeric(Sys.getenv("FIG1_DISEASE_BASE_SZ", unset = "17"))
  dis_col <- "#C0392B"   # Disease (red)
  hc_col  <- "#2C5F8A"   # Healthy Control (blue)

  dis <- readr::read_tsv(file.path(PREP_DIR, "top20_diseases.tsv"),
                         show_col_types = FALSE)
  if (nrow(dis) == 0) return("top20_diseases.tsv is empty")

  # Long format: each disease is one horizontal bar stacked from the red
  # "Disease" block (the disease samples) below the blue "Healthy Control"
  # block (healthy-control samples sharing a BioProject with the disease).
  # Only the top-15 disease statuses by disease-sample count are shown; the
  # aggregate "Other" status is excluded. Bars are sorted by TOTAL size
  # (n + hc_same_study), largest at the top (first factor level drawn bottom).
  dis <- dis %>%
    filter(status != "Other") %>%
    arrange(desc(n)) %>%
    slice_head(n = 15) %>%
    mutate(tot = n + hc_same_study) %>%
    arrange(tot) %>%
    mutate(status = factor(status, levels = status))
  plt <- dis %>%
    tidyr::pivot_longer(c(n, hc_same_study),
                        names_to = "group", values_to = "count") %>%
    mutate(group = ifelse(group == "n", "Disease", "Healthy Control"),
           group = factor(group, levels = c("Disease", "Healthy Control"))) %>%
    group_by(status) %>%
    mutate(low   = cumsum(count) - count,
           mid   = low + count / 2) %>%
    ungroup()

  p <- ggplot(plt, aes(x = count, y = status, fill = group)) +
    geom_col(width = 0.86, position = "stack", color = "white", linewidth = 0.15) +
    scale_x_continuous(
      labels = function(x) ifelse(x == 0, "0", paste0(x / 1000, "k")),
      expand = expansion(mult = c(0, 0.02))) +
    scale_fill_manual(values = c("Disease" = dis_col,
                                 "Healthy Control" = hc_col),
                      name = NULL, breaks = c("Disease", "Healthy Control")) +
    scale_y_discrete(labels = paste0(as.character(dis$status), " (",
                                    scales::comma(dis$tot), ")")) +
    labs(x = "Number of samples", y = NULL) +
    theme_classic(base_size = base_sz - 4, base_family = "sans") +
    theme(
      axis.text.y        = element_text(size = base_sz * 0.68, face = "bold",
                                        color = "#303030"),
      axis.text.x        = element_text(size = base_sz * 0.72, face = "bold",
                                        color = "#303030"),
      axis.title.x       = element_text(size = base_sz * 0.92, face = "bold",
                                        color = "#303030"),
      legend.position    = c(0.90, 0.10),
      legend.justification = c(1, 0),
      legend.title       = element_blank(),
      legend.text        = element_text(size = base_sz * 0.72, color = "#303030"),
      legend.key         = element_rect(fill = NA, color = NA),
      legend.key.size    = unit(3.5, "mm"),
      legend.background  = element_rect(fill = "white", color = "#303030",
                                       linewidth = 0.4),
      legend.margin      = margin(2, 6, 2, 3),
      plot.margin        = margin(4, 4, 4, 4)
    )

  ggplot2::ggsave(file.path(out_dir, panel_png["DISEASE"]), plot = p,
